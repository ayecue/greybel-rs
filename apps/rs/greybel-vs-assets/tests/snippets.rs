//! The game's scripts as greybel-vs's snippets, in `src/snippets.generated.ts`.

use greyhack_world_assets::Script;

use crate::support::{assert_up_to_date, greybel_vs};

#[test]
fn should_give_greybel_vs_the_games_scripts_as_snippets() {
    let path = greybel_vs().join("src/snippets.generated.ts");
    let entries: Vec<String> = Script::all()
        .iter()
        .map(|script| {
            let name = serde_json::to_string(script.command).expect("a string serializes");
            let source = serde_json::to_string(script.source).expect("a string serializes");

            format!("  {name}: {source},\n")
        })
        .collect();
    let generated = format!(
        "// Generated by greybel-vs-assets' tests from the game's scripts (greyhack-world-assets); do not edit.\n\n/** The source of each command of the game, by its name. */\nexport const SNIPPETS: Readonly<Record<string, string>> = {{\n{}}};\n",
        entries.concat()
    );

    assert_up_to_date(&path, &generated);
}
