import { WorkerHost } from 'duplex-driver-worker';
import { EditorChannel as DocumentsChannel, MemoryEditor } from 'greybel-documents-host-provider';
import { PageChannel } from 'greybel-io-web';
import {
  Continue,
  EditorChannel,
  EditorRouter,
  Environment,
  Evaluate,
  EvaluationFailure,
  Exit,
  Launch,
  LaunchFailure,
  Pause,
  Scopes,
  SetBreakpoints,
  SourceBreakpoint,
  StackTrace,
  Step,
  Terminate,
  Variables,
  type Evaluation,
  type LogMessage,
  type Scope,
  type SourceLocation,
  type StackFrame,
  type StepMode,
  type StopNotice,
  type Variable
} from 'greybel-runtime';
import runtimeScript from 'greybel-runtime-web/dist/index.js?url';
import { World } from 'greyhack-world-operations';
import { serveWasm } from 'wasm-host/worker';

import { filePath, fileUri, rootUri } from '../project/paths.js';
import { compiledRuntime } from './compiled-module.js';
import type { Terminal } from './terminal.js';

/** Optional import extensions in resolution order. */
const EXTENSIONS = ['src', 'gs', 'ms'];
/** Program memory limit in MiB; defaults to the project's `run.memoryLimit`. */
const MEMORY_LIMIT = 1024;
/** Binary name in the program user's home folder; defaults to the project's `run.programName`. */
const PROGRAM_NAME = 'myprogram';

export interface RunOptions {
  /** Project files keyed by URI. */
  readonly documents: ReadonlyMap<string, string>;
  /** Program entry-file path. */
  readonly entry: string;
  readonly params: readonly string[];
  /** Seed for the world generated by the page's game server. */
  readonly seed: string;
  readonly debug: boolean;
}

/** Running-program events emitted by the session. */
export interface SessionListener {
  onStop(notice: StopNotice): void;
  onLog(message: LogMessage): void;
}

class ListenerRouter extends EditorRouter {
  constructor(private readonly listener: SessionListener) {
    super();
  }

  override onStopNotice(message: StopNotice): void {
    this.listener.onStop(message);
  }

  override onLogMessage(message: LogMessage): void {
    this.listener.onLog(message);
  }
}

/**
 * Runs greybel-runtime-web in a worker for the page project. Connects program I/O to a page terminal, serves
 * in-memory files for imports, reports debugger stops, and accesses the page game server's world through
 * `world`.
 */
export class RuntimeSession {
  readonly #host: WorkerHost<Record<string, never>>;
  readonly #runtime: EditorChannel;
  readonly #documents = new MemoryEditor();

  constructor(terminal: Terminal, listener: SessionListener, world: MessagePort) {
    const worker = new Worker(runtimeScript);

    serveWasm(worker, compiledRuntime());
    this.#host = new WorkerHost(worker, {}, { ports: [{ protocol: World, port: world }] });
    this.#runtime = new EditorChannel(this.#host.transport).use(new ListenerRouter(listener));
    new PageChannel(this.#host.transport).use(terminal);
    new DocumentsChannel(this.#host.transport).use(this.#documents);
  }

  /** Runs the project from `options.entry` and returns its exit result. */
  run(options: RunOptions): Promise<Exit> {
    this.#documents.files.clear();
    for (const [uri, code] of options.documents) this.#documents.files.set(uri, code);

    return this.#runtime.send(
      new Launch({
        entry: fileUri(options.entry),
        root: rootUri,
        extensions: EXTENSIONS,
        environment: new Environment.Mock({ seed: options.seed, memoryLimit: MEMORY_LIMIT }),
        debug: options.debug,
        stopOnEntry: false,
        params: [...options.params],
        variables: {},
        strictMode: false,
        programName: PROGRAM_NAME
      })
    );
  }

  /** Replaces breakpoints for `uri` with one-based `lines`. */
  async setBreakpoints(uri: string, lines: readonly number[]): Promise<void> {
    await this.#runtime.send(
      new SetBreakpoints({
        uri,
        breakpoints: lines.map((line) => new SourceBreakpoint({ line }))
      })
    );
  }

  resume(): void {
    void this.#runtime.send(new Continue());
  }

  step(mode: StepMode): void {
    void this.#runtime.send(new Step({ mode }));
  }

  pause(): void {
    void this.#runtime.send(new Pause());
  }

  terminate(): void {
    void this.#runtime.send(new Terminate());
  }

  stackTrace(): Promise<StackFrame[]> {
    return this.#runtime.send(new StackTrace());
  }

  scopes(frame: number): Promise<Scope[]> {
    return this.#runtime.send(new Scopes({ frame }));
  }

  variables(reference: number): Promise<Variable[]> {
    return this.#runtime.send(new Variables({ reference }));
  }

  /** Evaluates `code` at the stop location; returns an expression value or undefined for statements. */
  evaluate(code: string): Promise<Evaluation | null> {
    return this.#runtime.send(new Evaluate({ code }));
  }

  close(): void {
    this.#host.close();
  }
}

/** Project source location displayed by the page. */
export function describeLocation(location: SourceLocation): string {
  const file = filePath(location.uri) ?? location.uri;

  return `${file}:${location.line}:${location.character}`;
}

/** Return a terminal description of how the program ended, or none when it completed. */
export function describeExit(exit: Exit): string | undefined {
  if (exit instanceof Exit.Crash) {
    const stack = exit.stack.map((location) => `\n  at ${describeLocation(location)}`).join('');

    return `Runtime error: ${exit.message}${stack}`;
  }

  if (exit instanceof Exit.Termination) return 'The program was stopped.';

  return undefined;
}

/** Format a launch, inspection, or evaluation failure for display on the page. */
export function describeFailure(error: unknown): string {
  const failure = error instanceof ChannelError ? (error.failure as unknown) : undefined;

  if (failure instanceof LaunchFailure.Invalid) {
    return `Prepare error: ${failure.message}${failure.location ? ` at ${describeLocation(failure.location)}` : ''}`;
  }

  if (failure instanceof LaunchFailure.Busy) return 'A program runs already.';
  if (failure instanceof LaunchFailure.Unavailable || failure instanceof LaunchFailure.Unreachable) {
    return "Grey Hack can't be reached from the browser.";
  }

  if (failure instanceof EvaluationFailure.CodeError) return failure.message;
  if (failure instanceof EvaluationFailure.ActiveProgram) return 'The program runs: pause it first.';

  return error instanceof Error ? error.message : String(error);
}
