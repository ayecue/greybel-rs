//! Public-address groups and the missions they carry (`IPGroupManager`).

use crate::WorldSeed;
use crate::network::address::is_group_reserved_ip;

const GROUP_SIZE: u32 = 10;
const GROUP_LABEL: &str = "ip-group-v1";
/// Number of groups searched for a mission (`IPGroupManager.GetRandomGroupForMission`).
pub const GROUP_COUNT: u32 = 429_496_729;
/// A zero-day group needs this many addresses (`IPGroupManager.GetRandomGroupForMission`).
pub const MIN_ZERO_DAY_GROUP: usize = 4;

/// Kind of mission a group of addresses carries (`TypeMission` and the `NOMISSION` entry of
/// `IPGroupManager.MissionCounts`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MissionKind {
    Secret,
    Grey,
    Black,
    White,
    ZeroDay,
    Procedural,
    PoliceProcedural,
    NoMission,
}

impl MissionKind {
    /// The kinds with the number of missions of each, in the order of `IPGroupManager.MissionCounts`.
    pub const COUNTS: [(Self, u32); 8] = [
        (Self::Secret, 10),
        (Self::Grey, 3),
        (Self::Black, 3),
        (Self::White, 3),
        (Self::ZeroDay, 1),
        (Self::Procedural, 3),
        (Self::PoliceProcedural, 3),
        (Self::NoMission, 30),
    ];

    /// The name the game uses as dictionary key and enum name.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Secret => "HIDDEN",
            Self::Grey => "GREY",
            Self::Black => "BLACK",
            Self::White => "WHITE",
            Self::ZeroDay => "ZERODAY",
            Self::Procedural => "PROCEDURAL",
            Self::PoliceProcedural => "POLICE_PROCEDURAL",
            Self::NoMission => "NOMISSION",
        }
    }

    /// The number of missions of this kind (`IPGroupManager.MissionCounts`).
    #[must_use]
    pub fn count(self) -> u32 {
        Self::COUNTS
            .iter()
            .find(|(kind, _)| *kind == self)
            .map_or(0, |(_, count)| *count)
    }

    /// Whether the missions of this kind are generated by `ProcMissionBuilder`
    /// (`MissionGen.IsProceduralMission`).
    #[must_use]
    pub const fn is_procedural(self) -> bool {
        matches!(self, Self::Procedural | Self::PoliceProcedural)
    }
}

/// The group of addresses `address` belongs to (`IPGroupManager.GetIPGroup`); `None` for an invalid address.
#[must_use]
pub fn ip_group(seed: &WorldSeed, address: &str) -> Option<Vec<String>> {
    let address = address.parse::<std::net::Ipv4Addr>().ok()?;

    Some(group_by_number(
        seed,
        seed.permute_u32(GROUP_LABEL, u32::from(address)) / GROUP_SIZE,
    ))
}

/// The mission of the group `group` and its index among the missions of its kind
/// (`IPGroupManager.GetMissionForGroup`); `None` for an empty group or an invalid address.
#[must_use]
pub fn mission_for_group(seed: &WorldSeed, group: &[String]) -> Option<(MissionKind, u32)> {
    let first = group.first()?.parse::<std::net::Ipv4Addr>().ok()?;

    Some(mission_of(
        seed.permute_u32(GROUP_LABEL, u32::from(first)) / GROUP_SIZE,
    ))
}

/// The group of mission `index` of `kind` found by searching from group number `start`, which the game draws at
/// random below [`GROUP_COUNT`] (`IPGroupManager.GetRandomGroupForMission`); `None` where the game throws.
#[must_use]
pub fn random_group_for_mission(
    seed: &WorldSeed,
    kind: MissionKind,
    index: u32,
    start: u32,
) -> Option<Vec<String>> {
    if index >= kind.count() {
        return None;
    }

    (0..GROUP_COUNT).find_map(|offset| {
        let number = (offset + start) % GROUP_COUNT;

        if mission_of(number) != (kind, index) {
            return None;
        }

        let group = group_by_number(seed, number);

        (kind != MissionKind::ZeroDay || group.len() >= MIN_ZERO_DAY_GROUP).then_some(group)
    })
}

fn group_by_number(seed: &WorldSeed, number: u32) -> Vec<String> {
    (0..GROUP_SIZE)
        .map(|offset| {
            seed.depermute_u32(
                GROUP_LABEL,
                number.wrapping_mul(GROUP_SIZE).wrapping_add(offset),
            )
        })
        .map(|address| std::net::Ipv4Addr::from(address).to_string())
        .filter(|address| !is_group_reserved_ip(address))
        .collect()
}

/// `IPGroupManager.GetMission`.
fn mission_of(number: u32) -> (MissionKind, u32) {
    let total: u32 = MissionKind::COUNTS.iter().map(|(_, count)| count).sum();
    let mut offset_left = number % total;

    for (kind, count) in MissionKind::COUNTS {
        if offset_left < count {
            return (kind, offset_left);
        }

        offset_left -= count;
    }

    (MissionKind::NoMission, 0)
}
