//! Operation messages that identify their originating program.

use greyhack_world_programs::protocol::*;

/// Program message carrying its source program ID.
pub trait Operation {
    /// Source program ID, or `None` for a program-start message.
    fn program(&self) -> Option<ProgramId>;
}

impl Operation for StartProgram<'_> {
    fn program(&self) -> Option<ProgramId> {
        None
    }
}

/// Implements [`Operation`] for messages with a `program` field, handling borrowed-text messages before
/// owned messages.
macro_rules! operations {
    (borrowed: [$($borrowed:ident),* $(,)?], owned: [$($owned:ident),* $(,)?] $(,)?) => {
        $(
            impl Operation for $borrowed<'_> {
                fn program(&self) -> Option<ProgramId> {
                    Some(self.program)
                }
            }
        )*
        $(
            impl Operation for $owned {
                fn program(&self) -> Option<ProgramId> {
                    Some(self.program)
                }
            }
        )*
    };
}

