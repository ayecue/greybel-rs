use crate::types::{Output, PrintOptions};

const NEW_LINE: char = '\n';

/// Cursor state after output, used to select the replacement erase target: `Blank` erases nothing, `InLine`
/// erases the current line, and `BelowLine` erases the previous line.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum LineCursor {
    #[default]
    Blank,
    InLine,
    BelowLine,
}

impl LineCursor {
    /// Computes the cursor state produced by printing `text` with `options`.
    #[must_use]
    pub fn after(self, text: &str, options: PrintOptions) -> Self {
        if options.new_line || text.ends_with(NEW_LINE) {
            Self::BelowLine
        } else if !text.is_empty() || options.replace {
            Self::InLine
        } else {
            self
        }
    }
}

/// Terminal lines generated by program output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TextScreen {
    lines: Vec<String>,
    cursor: LineCursor,
}

impl Default for TextScreen {
    fn default() -> Self {
        Self {
            lines: vec![String::new()],
            cursor: LineCursor::Blank,
        }
    }
}

impl TextScreen {
    #[must_use]
    pub fn lines(&self) -> &[String] {
        &self.lines
    }

    /// Joins lines with newlines and omits a trailing newline.
    #[must_use]
    pub fn text(&self) -> String {
        self.lines.join("\n")
    }

    pub fn apply(&mut self, batch: &[Output]) {
        for output in batch {
            match output {
                Output::Print { text, options } => self.print(text, *options),
                Output::Clear => self.clear(),
            }
        }
    }

    pub fn print(&mut self, text: &str, options: PrintOptions) {
        if options.replace {
            self.erase_line();
        }

        let mut parts = text.split(NEW_LINE);

        if let (Some(first), Some(last)) = (parts.next(), self.lines.last_mut()) {
            last.push_str(first);
        }

        self.lines.extend(parts.map(str::to_owned));
        if options.new_line {
            self.lines.push(String::new());
        }

        self.cursor = self.cursor.after(text, options);
    }

    pub fn clear(&mut self) {
        *self = Self::default();
    }

    fn erase_line(&mut self) {
        match self.cursor {
            LineCursor::Blank => return,
            LineCursor::BelowLine if self.lines.len() > 1 => {
                self.lines.pop();
            }
            LineCursor::InLine | LineCursor::BelowLine => {}
        }

        if let Some(last) = self.lines.last_mut() {
            last.clear();
        }
    }
}
