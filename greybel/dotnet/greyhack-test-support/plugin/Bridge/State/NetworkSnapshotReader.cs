/// <summary>
/// Reads game network state for simulation: every LAN device and computer (<c>NetworkLan</c>) in game search order,
/// including router settings and port tables plus computer users, files, and ports.
/// </summary>
internal static class NetworkSnapshotReader
{
    private static ContactSnapshot ReadContact(Router router)
    {
        Persona admin = router.GetAdmin();
        return admin == null
            ? null
            : new ContactSnapshot(
                admin.GetNombreCompleto(),
                admin.GetMailAdress(),
                admin.npcInfo.GetPhoneNumber()
            );
    }

    private static ContactSnapshot ReadRentalContact(NetworkLan lan)
    {
        if (!lan.IsSuperAdminRental())
        {
            return null;
        }
        NetworkLan.SuperAdminRentalHelper admin = lan.GetSuperAdminRental();
        return new ContactSnapshot(admin.npcCompleteName, admin.mailAddress, admin.phoneNumber);
    }

    /// <summary>Ticks of 1970-01-01, the zero of the snapshot's file dates.</summary>
    private const long UnixEpochTicks = 621355968000000000L;

    /// <summary>
    /// Gets the network containing <paramref name="player"/>'s computer. Accessing a router or computer not yet
    /// generated by the game generates it, matching normal network access.
    /// </summary>
    public static NetworkSnapshot Read(
        Computer player,
        string debugUser,
        string debugPassword,
        string ctfEventName,
        string trafficAccidentAt,
        string trafficAccidentDriver
    )
    {
        Router playerRouter = player.GetMainRouter();
        Router router =
            ServerMap.Singleton.GetRouter(new IP(playerRouter.GetPublicIP()), false)
            ?? playerRouter;
        NetworkLan lan = router.GetNetworkLan();
        ServerMap.RouterNode routerNode = Database.Singleton.GetRouterNode(router.GetPublicIP());
        List<LanNodeSnapshot> nodes = new List<LanNodeSnapshot>();

        ReadDevice(router, lan, lan.routerDevice, null, player.GetID(), nodes);

        PlayerComputer playerComputer = (PlayerComputer)player;
        EconomySnapshot economy = EconomySnapshotReader.Read(playerComputer);

        return new NetworkSnapshot(
            router.GetPublicIP(),
            router.GetTipoRed().ToString(),
            router.GetWebAddress() ?? "",
            nodes,
            NpcSnapshotReader.ReadAdmin(router),
            ReadContact(router),
            ReadRentalContact(lan),
            NpcSnapshotReader.ReadNpcs(router, lan),
            NpcSnapshotReader.ReadTraffic(
                router,
                lan,
                trafficAccidentAt,
                trafficAccidentDriver
            ),
            economy.PlayerBank,
            AccountSnapshotReader.ReadMail(playerComputer.GetPlayerConfigOS().GetMailAccount()),
            AccountSnapshotReader.ReadMailAddress(
                "recipient@" + router.GetDomain(),
                "recipientpass"
            ),
            ClockServer.Singleton.GetFechaCompleta(),
            AccountSnapshotReader.ReadDebug(player, debugUser, debugPassword),
            AccountSnapshotReader.ReadCtf(player, ctfEventName),
            economy.Banks,
            economy.Coins,
            economy.Wallets,
            economy.Offers,
            router.GetNetworkLan().disabledNetwork,
            router.GetNetworkLan().IsSuperAdminRental(),
            (byte)router.GetNetworkLan().netSpeed,
            new List<float> { routerNode.routerPos.x, routerNode.routerPos.y },
            Convert.FromBase64String(Database.Singleton.GetWorldSecret()),
            BankFixture.Read(playerComputer.GetPlayerID()),
            VersionsControl
                .Singleton.GetLastLibs()
                .Values.Select(library => JsonConvert.SerializeObject(library))
                .ToList()
        );
    }

    /// <summary>
    /// Traverses <paramref name="device"/>, its computers, and child devices in <c>NetworkLan.FindDevice</c> order.
    /// </summary>
    private static void ReadDevice(
        Router main,
        NetworkLan lan,
        NetworkLan.Device device,
        uint? parent,
        string player,
        List<LanNodeSnapshot> nodes
    )
    {
        uint index = (uint)nodes.Count;

        nodes.Add(
            new LanNodeSnapshot(
                parent,
                device.localIp,
                "",
                false,
                device.IsHub()
                    ? new LanNodeKind.Hub()
                    : new LanNodeKind.Router(ReadRouter(main, device))
            )
        );

        foreach (LanPcInfo computer in device.GetLanPcInfos())
        {
            nodes.Add(
                new LanNodeSnapshot(
                    index,
                    computer.localIp,
                    computer.gateway ?? "",
                    computer.IsHidden(lan),
                    new LanNodeKind.Computer(ReadComputer(main, computer, player))
                )
            );
        }

        foreach (NetworkLan.Device child in device.GetDevices())
        {
            ReadDevice(main, lan, child, index, player, nodes);
        }
    }

    private static RouterSnapshot ReadRouter(Router main, NetworkLan.Device device)
    {
        Router router =
            device.localIp == main.GetLocalIP() ? main : main.GetLanRouter(device.localIp);
        NetworkLan.RouterNet routerNet = (NetworkLan.RouterNet)device;
        bool wifi = routerNet.wifiEnabled && !string.IsNullOrEmpty(router.GetBssid());
        List<FileSnapshot> files = new List<FileSnapshot>();

        ReadFolder(router.GetFileSystem().GetCarpetaRaiz(), files);

        return new RouterSnapshot(
            device.IsSwitch() ? "SWITCH" : "ROUTER",
            wifi ? router.GetBssid() : null,
            wifi ? router.GetEssid() : null,
            router.GetPassword() ?? "",
            ReadKernelVersion(router),
            ReadKernelContent(router),
            device
                .firewallRules.Select(rule => new FirewallRuleSnapshot(
                    rule.action.ToString(),
                    ReadRuleField(rule.port),
                    ReadRuleField(rule.sourceAddress),
                    ReadRuleField(rule.destAddress)
                ))
                .ToList(),
            router
                .GetConfigOS()
                .puertos.allPorts.Select(port => ReadTablePort(main, port))
                .ToList(),
            ReadUsers(router),
            files
        );
    }

    private static string ReadKernelVersion(Router router)
    {
        FileSystem.Archivo kernel = router.GetFileSystem().GetArchivo("/lib/kernel_router.so");

        if (kernel == null || !kernel.IsTypeFile(FileSystem.Fichero.TypeFile.Library))
        {
            return "";
        }
        try
        {
            return JsonConvert.DeserializeObject<Library>(kernel.GetContenido()).GetStrVersion();
        }
        catch (JsonException)
        {
            return "";
        }
    }

    private static string ReadKernelContent(Router router)
    {
        return router.GetFileSystem().GetArchivo("/lib/kernel_router.so")?.GetContenido() ?? "";
    }

    internal static string ReadRuleField(HwFirewallRule.Rule field)
    {
        return field.status == HwFirewallRule.Rule.Status.ANY ? "Any" : field.GetFieldValue();
    }

    /// <summary>
    /// The service of <c>port</c> is its own <c>Puerto.ID</c>, and its version the one <c>Router.GetPortVersion</c>
    /// reads from the service library, <c>unknown</c> while that library is missing or invalid (the port stays in
    /// the game's tables after its library is renamed).
    /// </summary>
    private static (string Service, string Version) ReadPortService(Router main, Puerto port)
    {
        try
        {
            string[] words = main.GetPortVersion(port).Split(' ');

            return (port.ID.ToString(), words.Length > 1 ? words[1] : "unknown");
        }
        catch (JsonException)
        {
            return (port.ID.ToString(), "unknown");
        }
    }

    /// <summary>Router port-table entry with its service and version, see <c>ReadPortService</c>.</summary>
    internal static TablePortSnapshot ReadTablePort(Router main, Puerto port)
    {
        (string service, string version) = ReadPortService(main, port);

        return new TablePortSnapshot(
            (ushort)port.externalPort,
            port.lanIP ?? "",
            (ushort)port.internalPort,
            service,
            version,
            port.isClosed,
            port.isVisible
        );
    }

    private static List<UserSnapshot> ReadUsers(Computer computer)
    {
        return computer
            .GetUsers()
            .Select(user => new UserSnapshot(
                user.nombreUsuario,
                user.passPlano,
                user.grupos.ToList(),
                user.isDeletable
            ))
            .ToList();
    }

    private static ComputerSnapshot ReadComputer(Router main, LanPcInfo info, string player)
    {
        Computer computer = main.GetComputer(info.localIp);
        List<UserSnapshot> users = ReadUsers(computer);
        List<ProcessSnapshot> processes = computer
            .GetProcesos()
            .Select(process => new ProcessSnapshot(
                process.nombreProceso,
                process.nombreUser,
                process.isTerminal,
                process.ramUsedMb
            ))
            .ToList();
        List<Persona> npcs = new List<Persona>();
        if (!computer.IsSpawnedByPlayer() && !computer.IsRouter())
        {
            npcs.AddRange(computer.GetConfigOS().personas);
        }
        List<string> activeUsers = npcs.Where(persona =>
                persona != null && persona.IsLogged() && !persona.npcInfo.IsDeadOrFired()
            )
            .Select(persona => persona.GetNombreUser())
            .Distinct()
            .ToList();
        List<PortSnapshot> ports = computer
            .GetConfigOS()
            .puertos.allPorts.Select(port => ReadPort(main, info.localIp, port))
            .ToList();
        List<FileSnapshot> files = new List<FileSnapshot>();

        ReadFolder(computer.GetFileSystem().GetCarpetaRaiz(), files);

        List<NetCardSnapshot> netCards = computer
            .GetHardware()
            .networkDevices.Select(card => new NetCardSnapshot(
                card.name,
                card.isWifi,
                card.monitorSupport,
                card.monitorEnabled
            ))
            .ToList();

        return new ComputerSnapshot(
            info.typeDevice.ToString(),
            computer.GetConfigOS().GetNombreMaquina(),
            computer.GetID() == player,
            users,
            processes,
            activeUsers,
            ports,
            files,
            netCards,
            computer.GetConfigOS().GetActiveNetCard().ToString(),
            computer
                .GetConfigOS()
                .GetSavedNetworks()
                .Select(network => new SavedNetworkSnapshot(
                    network.bssid,
                    network.essid,
                    network.password,
                    network.publicIp
                ))
                .ToList(),
            computer.GetTipoRed().ToString(),
            computer is SmartAppliance appliance ? ReadSmartAppliance(appliance) : null,
            computer.GetHardware().hardDisk.GetSizeMB(),
            (computer as PlayerComputer)?.GetPlayerConfigOS().rentalHomeIP ?? "",
            computer.GetConfigOS().IsRebooting(),
            (uint)computer.GetHardware().GetTotalMemoryRam(),
            computer.GetHardware().gpu?.health ?? 0,
            computer.GetHardware().gpu?.hashrate ?? 0
        );
    }

    private static SmartApplianceSnapshot ReadSmartAppliance(SmartAppliance appliance)
    {
        SmartAppConfigOS settings = (SmartAppConfigOS)appliance.GetConfigOS();
        SmartAppliance.Model model = appliance.GetModel();

        return new SmartApplianceSnapshot(
            model.GetName(),
            model.GetReqPower(),
            model.GetReqTemp(),
            (int)GameField.AppliancePower.GetValue(settings),
            (int)GameField.ApplianceTemperature.GetValue(settings),
            settings.IsAlarmEnabled(),
            settings.IsOverrideSettingsEnabled(),
            settings.IsBroken()
                ? ((DateTime)GameField.ApplianceRecoveryTime.GetValue(settings)).ToString(
                    "dd/MMM/yyyy - HH:mm",
                    CultureInfo.InvariantCulture
                )
                : null
        );
    }

    /// <summary>Gets a port with its service and version, see <c>ReadPortService</c>.</summary>
    private static PortSnapshot ReadPort(Router main, string localIp, Puerto port)
    {
        Puerto lanPort = new Puerto(
            port.ID,
            port.internalPort,
            port.externalPort,
            port.isClosed,
            port.isVisible,
            localIp
        );
        (string service, string version) = ReadPortService(main, lanPort);

        return new PortSnapshot(
            (ushort)port.internalPort,
            service,
            version,
            port.isClosed,
            port.isVisible
        );
    }

    internal static void ReadFolder(FileSystem.Carpeta folder, List<FileSnapshot> files)
    {
        foreach (FileSystem.Carpeta child in folder.GetCarpetas())
        {
            files.Add(ReadEntry(child, true, "", false));
            ReadFolder(child, files);
        }

        foreach (FileSystem.Archivo file in folder.GetArchivos())
        {
            files.Add(ReadEntry(file, false, file.GetContenido() ?? "", file.IsBinario()));
        }
    }

    private static FileSnapshot ReadEntry(
        FileSystem.Fichero entry,
        bool folder,
        string content,
        bool binary
    )
    {
        return new FileSnapshot(
            entry.GetRuta(),
            folder,
            entry.GetNameOwner(),
            entry.GetNameGroup(),
            entry.GetStrPermisos(),
            (byte)(FileSystem.Fichero.TypeFile)GameField.FileType.GetValue(entry),
            binary,
            content,
            (ulong)System.Math.Max(0L, (long)GameField.FileSize.GetValue(entry)),
            entry.GetComando() ?? "",
            entry.GetSymLink() ?? "",
            (ulong)
                Math.Max(
                    0L,
                    (entry.GetTimestamp().Ticks - UnixEpochTicks) / TimeSpan.TicksPerSecond
                ),
            entry.isProtected,
            entry is FileSystem.Archivo archivo ? archivo.GetEncryptPassword() : ""
        );
    }
}
