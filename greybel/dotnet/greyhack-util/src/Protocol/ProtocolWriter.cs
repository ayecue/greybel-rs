using System.Text.RegularExpressions;
using GreyHackUtil.Contracts;

namespace GreyHackUtil.Protocol;

/// <summary>Generates the duplex protocol for game messages at <c>protocols/greyhack/&lt;major&gt;.&lt;minor&gt;.protocol</c>.</summary>
public static partial class ProtocolWriter
{
    public const string ProtocolName = "GreyHack";
    public const string Channel = "greyhack";
    public const string Provider = "MessageHook";
    public const string Client = "Greybel";
    private const string Limit = "16MiB";

    private static readonly string[] Tags =
    [
        "/// Grey Hack version from which these messages were generated.",
        "tag game_version: string on protocol;",
        "/// Game CLR type stored in the field positional parameter.",
        "tag game_param_type: string on field;",
        "/// Field is omitted, not null, when it has no value.",
        "tag game_param_optional on field;",
        "/// Game message ID: `IdServer` for provider messages and `IdClient` for client messages.",
        "tag game_message_id: u32 on message;",
        "/// ID of a plugin-defined message (greybel/contracts/extension.json).",
        "tag plugin_message_id: u32 on message;",
        "/// Field containing the PIDs of the windows targeted by the message.",
        "tag pid on field;",
        "/// Struct field name in the game JSON.",
        "tag game_field_name: string on field;",
    ];

    public static string Generate(ContractSet contracts, string? output = null)
    {
        var previous = ReadPrevious(output);
        var writer = new CodeWriter();
        writer.WriteLine(
            "// Generated by greybel/dotnet/greyhack-util from greybel/contracts. Do not edit: run `make contracts` or"
        );
        writer.WriteLine("// `make generate` in greybel/dotnet/.");
        writer.WriteLine("use core 1.0;");
        writer.WriteLine();
        foreach (string line in Tags)
        {
            writer.WriteLine(line);
        }
        writer.WriteLine();
        writer.WriteLine(
            $"/// Grey Hack messages exchanged between greybel and the game through the message hook plugin (Grey Hack {contracts.GameVersion})."
        );
        writer.WriteLine($"@game_version(\"{contracts.GameVersion}\")");
        using (writer.OpenBlock($"protocol {ProtocolName} = \"{Channel}\" {{", "}"))
        {
            writer.WriteLine($"limit {Limit};");
            writer.WriteLine();
            writer.WriteLine("/// Message hook plugin that forwards received messages to the game.");
            WriteBlock(writer, "provider", Provider, contracts.Server, previous);
            writer.WriteLine();
            writer.WriteLine("/// greybel client that receives game messages forwarded by the plugin.");
            WriteBlock(writer, "client", Client, contracts.Client, previous);
        }
        foreach (
            FieldType fieldType in contracts
                .FieldTypes.Where(fieldType =>
                    fieldType.Type == ValueKind.Struct
                    || (
                        fieldType.Type == ValueKind.Enum
                        && fieldType.Members!.Values.All(value => value >= 0)
                    )
                )
                .GroupBy(fieldType => ProtocolNameTable.ToTypeName(fieldType))
                .Select(group => group.First())
        )
        {
            writer.WriteLine();
            Declare(writer, fieldType);
        }
        return writer.ToString();
    }

    public static IReadOnlyList<Message> Order(Direction direction, IReadOnlyList<string>? before)
    {
        var messages = direction.TypedMessages.ToList();
        if (before == null)
        {
            return messages;
        }
        var byName = messages.ToDictionary(message => message.Name);
        if (before.FirstOrDefault(name => !byName.ContainsKey(name)) is string gone)
        {
            throw new ContractException(
                $"{direction.Name}: {gone} is gone since the version before, which takes a new major"
            );
        }
        return
        [
            .. before.Select(name => byName[name]),
            .. messages.Where(message => !before.Contains(message.Name)),
        ];
    }

    private static void WriteBlock(
        CodeWriter writer,
        string role,
        string peer,
        Direction direction,
        Dictionary<string, List<string>>? previous
    )
    {
        IReadOnlyList<Message> messages = Order(direction, previous?.GetValueOrDefault(peer));
        using (writer.OpenBlock($"{role} {peer} {{", "}"))
        {
            foreach (Message message in messages)
            {
                string handler =
                    message.Handler != null ? $"; handled by `{message.Handler}`"
                    : message.Senders != null
                        ? $"; sent with the layout used by `{string.Join("`, `", message.Senders)}`"
                    : "";
                writer.WriteLine(
                    message.Origin == Origin.Game
                        ? $"/// Game message `{direction.IdEnum}.{message.Name}`{handler}."
                        : $"/// Plugin-defined message `{message.Name}`{handler}."
                );
                writer.WriteLine(
                    message.Origin == Origin.Game
                        ? $"@game_message_id({message.Id})"
                        : $"@plugin_message_id({message.Id})"
                );
                var fields = GetFields(message);
                if (fields.Count == 0)
                {
                    writer.WriteLine($"message {message.Name} {{}}");
                    continue;
                }
                using (writer.OpenBlock($"message {message.Name} {{", "}"))
                {
                    foreach (var (field, name) in fields)
                    {
                        string pid = field == message.Window ? " @pid" : "";
                        string optional = field.Optional ? " @game_param_optional" : "";
                        writer.WriteLine($"/// Game identifier `{field.Name}`.");
                        writer.WriteLine(
                            $"@game_param_type(\"{field.FieldType.ClrType}\"){optional}{pid} {name}: {ToProtocolType(field)},"
                        );
                    }
                }
            }
        }
    }

    public static List<(Field Field, string Name)> GetFields(Message message)
    {
        var fields = message
            .Fields!.Select(field => (field, ProtocolNameTable.ToFieldName(field.Name)))
            .ToList();
        foreach (
            var group in fields.GroupBy(field => field.Item2).Where(group => group.Count() > 1)
        )
        {
            throw new ContractException(
                $"{message.Name}: {string.Join(" and ", group.Select(field => field.field.Name))} are both {group.Key} in the protocol"
            );
        }
        return fields;
    }

    public static string ToProtocolType(Field field) =>
        ToProtocolType(field.FieldType) + (field.Optional || field.FieldType.Nullable ? "?" : "");

    public static string ToProtocolType(FieldType fieldType) =>
        fieldType.Type switch
        {
            ValueKind.String => "string",
            ValueKind.Int32 => "i32",
            ValueKind.Int64 => "i64",
            ValueKind.UInt64 => "u64",
            ValueKind.Bool => "bool",
            ValueKind.Float32 => "f32",
            ValueKind.Float64 => "f64",
            ValueKind.Bytes => "bytes",
            ValueKind.Int32Array => "list<i32>",
            ValueKind.StringList => "list<string>",
            ValueKind.Enum when fieldType.Members!.Values.Any(value => value < 0) => "i32",
            ValueKind.Enum or ValueKind.Struct => ProtocolNameTable.ToTypeName(fieldType),
            ValueKind kind => throw new ContractException(
                $"no protocol type for value type {kind}"
            ),
        };

    private static string ToProtocolType(ValueKind kind) =>
        kind switch
        {
            ValueKind.Enum or ValueKind.Struct => throw new ContractException(
                $"a struct's field is of value type {kind}"
            ),
            _ => ToProtocolType(new FieldType { Type = kind }),
        };

    private static void Declare(CodeWriter writer, FieldType fieldType)
    {
        string name = ProtocolNameTable.ToTypeName(fieldType);
        writer.WriteLine($"/// Game identifier `{fieldType.ClrType}`.");
        if (fieldType.Type == ValueKind.Enum)
        {
            var members =
                fieldType.Members
                ?? throw new ContractException(
                    $"{fieldType.Key} is an enumeration without members"
                );
            using (writer.OpenBlock($"enum {name} {{", "}"))
            {
                foreach (var (member, value) in members.OrderBy(member => member.Value))
                {
                    if (value is < 0 or > uint.MaxValue)
                    {
                        throw new ContractException(
                            $"{fieldType.ClrType}.{member} is {value}, which no protocol enumeration holds"
                        );
                    }
                    writer.WriteLine($"/// Game identifier `{member}`.");
                    writer.WriteLine($"{ProtocolNameTable.ToMemberName(member)} = {value},");
                }
            }
            return;
        }
        var fields =
            fieldType.Fields
            ?? throw new ContractException($"{fieldType.Key} is a struct without fields");
        using (writer.OpenBlock($"struct {name} {{", "}"))
        {
            foreach (StructField field in fields)
            {
                writer.WriteLine(
                    $"@game_field_name(\"{field.Name}\") {ProtocolNameTable.ToFieldName(field.Name)}: {ToProtocolType(field.Type)},"
                );
            }
        }
    }

    private static Dictionary<string, List<string>>? ReadPrevious(string? output)
    {
        if (output == null)
        {
            return null;
        }
        string? folder = Path.GetDirectoryName(Path.GetFullPath(output));
        if (
            ParseVersion(output) is not var (major, minor)
            || folder == null
            || !Directory.Exists(folder)
        )
        {
            return null;
        }
        string? before = Directory
            .GetFiles(folder, $"{major}.*.protocol")
            .Select(path => (path, version: ParseVersion(path)))
            .Where(file =>
                file.version is var (fileMajor, fileMinor)
                && fileMajor == major
                && fileMinor < minor
            )
            .OrderByDescending(file => file.version!.Value.Minor)
            .Select(file => file.path)
            .FirstOrDefault();
        if (before == null)
        {
            return null;
        }
        var blocks = new Dictionary<string, List<string>>();
        List<string>? block = null;
        foreach (string line in File.ReadLines(before))
        {
            if (GetPeerLineRegex().Match(line) is { Success: true } peer)
            {
                block = blocks[peer.Groups[1].Value] = [];
            }
            else if (
                GetMessageLineRegex().Match(line) is { Success: true } message
                && block != null
            )
            {
                block.Add(message.Groups[1].Value);
            }
        }
        return blocks;
    }

    private static (int Major, int Minor)? ParseVersion(string path)
    {
        var match = GetVersionFileRegex().Match(Path.GetFileName(path));
        return match.Success
            ? (int.Parse(match.Groups[1].Value), int.Parse(match.Groups[2].Value))
            : null;
    }

    [GeneratedRegex(@"^(\d+)\.(\d+)\.protocol$")]
    private static partial Regex GetVersionFileRegex();

    [GeneratedRegex(@"^\s*(?:provider|client) (\w+) \{")]
    private static partial Regex GetPeerLineRegex();

    [GeneratedRegex(@"^\s*message (\w+) \{")]
    private static partial Regex GetMessageLineRegex();
}
