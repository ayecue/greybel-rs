//! C# protocol binding generator for the provider-side core in `duplex/dotnet/duplex-core`. Generates message and
//! data types, binary codecs, protocol metadata, notification routers, and provider channels.

mod code;
mod codec;
mod declarations;
mod tags;
mod types;

use std::fmt;

use code::Code;
use declarations::DeclarationBuilder;
pub use duplex_protocol::{MinorVersionTable, Role, VersionHistory};
use duplex_protocol::{Plan, Status};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Content {
    Types,
    Protocol,
}

/// C# module for one protocol definition major version.
pub struct Module<'a> {
    major: MinorVersionTable<'a>,
    namespace: &'a str,
    content: Content,
}

impl<'a> Module<'a> {
    /// Returns a module declaring major-version types and binary codecs in `namespace`.
    #[must_use]
    pub fn types(major: MinorVersionTable<'a>, namespace: &'a str) -> Self {
        Self {
            major,
            namespace,
            content: Content::Types,
        }
    }

    /// Returns a module declaring types, messages, protocol metadata, and provider router/channel APIs in
    /// `namespace`.
    ///
    /// # Panics
    ///
    /// Panics if the major lacks a protocol, its latest version is unavailable, or the protocol declares a handshake.
    /// The C# core does not support handshakes.
    #[must_use]
    pub fn protocol(major: MinorVersionTable<'a>, namespace: &'a str) -> Self {
        let latest = major.latest();
        let protocol = latest
            .definition
            .protocol()
            .unwrap_or_else(|| panic!("{} declares a protocol", latest.version));

        assert!(
            *latest.definition.status() != Status::Unavailable,
            "{} is supported",
            latest.version
        );
        assert!(
            !protocol.handshake.is_declared(),
            "`{}` has a handshake, which the C# core can't serve yet",
            protocol.name
        );

        Self {
            major,
            namespace,
            content: Content::Protocol,
        }
    }
}

impl fmt::Display for Module<'_> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        let latest = self.major.latest();
        let plan = Plan::of(self.major);
        let declarations = DeclarationBuilder::new(&plan);
        let mut code = Code::default();
        let source = plan.definition.protocol().map_or_else(
            || "a definition".to_owned(),
            |protocol| format!("the protocol `{}`", protocol.name),
        );

        code.line(format!(
            "// Generated by duplex-cs from {source} {}.{}; do not edit.",
            latest.version.major, latest.version.minor
        ));
        code.line("#nullable enable");
        code.line("");
        code.line(format!("namespace {};", self.namespace));
        code.line("");
        declarations.patterns(&mut code);
        declarations.constants(&mut code);
        declarations.types(&mut code);
        if self.content == Content::Protocol {
            let protocol = plan.protocol.as_ref().expect("check when made");

            declarations.messages(&mut code, protocol);
            declarations.protocol(&mut code, protocol);
            DeclarationBuilder::provider(&mut code, protocol);
        }

        formatter.write_str(&code.finish())
    }
}
